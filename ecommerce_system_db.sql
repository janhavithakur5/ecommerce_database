MIN(SALES) AS LOWEST_SALES FROM SALES;

-- 18. Calculate total revenue generated by each product .
SELECT PROD_ID, SUM(QUANTITY*SALES) AS TOTAL_REVENUE  FROM SALES GROUP BY PROD_ID;

-- 19. Find total sales generated by each product category.
SELECT P.CATEGORY,SUM(S.SALES) AS TOTAL_SALES
FROM PRODUCT AS P
JOIN SALES AS S
ON P.PROD_ID = S.PROD_ID
GROUP BY P.CATEGORY;

-- 20. IDNETIFY THE PRODUCT CATEGORY GENERATING THE HIGHEST REVENUE.
SELECT P.CATEGORY,SUM(QUANTITY*S.SALES) AS TOTAL_REVENUE
FROM PRODUCT AS P
JOIN SALES AS S
ON P.PROD_ID = S.PROD_ID
GROUP BY P.CATEGORY
ORDER BY TOTAL_REVENUE DESC LIMIT 1;

-- 21. Find total revenue generated by each location.
SELECT O.SHIPPING_ADDRESS,SUM(QUANTITY*S.SALES) AS TOTAL_REVENUE
FROM ORDERS AS O
JOIN SALES AS S
ON O.ORDER_ID = S.ORDER_ID
GROUP BY O.SHIPPING_ADDRESS;

-- 22. Calulate total profit generated by each location.
SELECT O.SHIPPING_ADDRESS,SUM(S.PROFIT) AS TOTAL_PROFIT
FROM ORDERS AS O
JOIN SALES AS S
ON O.ORDER_ID = S.ORDER_ID
GROUP BY O.SHIPPING_ADDRESS;

-- 23. Find the number of orders in each order status. 
